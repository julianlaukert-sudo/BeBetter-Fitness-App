-- V2: Tabelle nutzer (Konto, BCrypt-Hash, Rolle).
-- Struktur exakt wie in der Referenz Test_BeBetter_Prototyp-2 (Teamentscheidung).
CREATE TABLE nutzer (
                        id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name           VARCHAR(50)  NOT NULL,
                        email          VARCHAR(255) NOT NULL,
                        passwort_hash  VARCHAR(100) NOT NULL,
                        rolle          VARCHAR(10)  NOT NULL,
                        registriert_am TIMESTAMP WITH TIME ZONE NOT NULL,
                        CONSTRAINT uk_nutzer_email UNIQUE (email),
                        CONSTRAINT ck_nutzer_rolle CHECK (rolle IN ('USER', 'ADMIN'))
);