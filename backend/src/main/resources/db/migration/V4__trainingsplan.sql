CREATE TABLE trainingsplan (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               nutzer_id BIGINT NOT NULL REFERENCES nutzer(id),
                               wochen_start DATE NOT NULL,
                               wochen_ende DATE NOT NULL,
                               erstellt_am TIMESTAMP WITH TIME ZONE NOT NULL,
                               CONSTRAINT uq_plan_woche UNIQUE (nutzer_id, wochen_start)
);

CREATE TABLE einheit (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         plan_id BIGINT NOT NULL REFERENCES trainingsplan(id) ON DELETE CASCADE,
                         label VARCHAR(1) NOT NULL CHECK (label IN ('A','B','C')),
                         position_nr INTEGER NOT NULL CHECK (position_nr BETWEEN 1 AND 3),
                         datum DATE NOT NULL,
                         UNIQUE (plan_id, position_nr)
);

CREATE TABLE plan_uebung (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             einheit_id BIGINT NOT NULL REFERENCES einheit(id) ON DELETE CASCADE,
                             position_nr INTEGER NOT NULL CHECK (position_nr BETWEEN 1 AND 5),
                             exercise_id VARCHAR(20) NOT NULL,
                             koerperteil VARCHAR(20) NOT NULL,
                             saetze INTEGER NOT NULL,
                             wiederholungen VARCHAR(10) NOT NULL,
                             gewicht_kg NUMERIC(5,1),
                             UNIQUE (einheit_id, position_nr)
);