ALTER TABLE trainingsplan ADD COLUMN ausgewertet BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE einheit ADD COLUMN uebernommen BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE markierung (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            plan_uebung_id BIGINT NOT NULL UNIQUE REFERENCES plan_uebung(id) ON DELETE CASCADE,
                            datum DATE NOT NULL,
                            geschafft BOOLEAN NOT NULL,
                            gewicht_kg NUMERIC(5,1),
                            wiederholungen INTEGER NOT NULL CHECK (wiederholungen BETWEEN 0 AND 200),
                            automatisch BOOLEAN NOT NULL,
                            erstellt_am TIMESTAMP WITH TIME ZONE NOT NULL,
                            CHECK (gewicht_kg IS NULL OR gewicht_kg BETWEEN 0 AND 500)
);